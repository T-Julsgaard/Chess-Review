// Reproducible promotion: relocate imports and normalize trailing newlines only.
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
const root = path.resolve(import.meta.dirname, '..');
const entry = 'research/experiments/E080-pawn-shield-defense/code/shield.mjs';
const destination = 'lib/concepts/detectors';
const sources = new Map();
const hash = text => createHash('sha256').update(text).digest('hex');
const name = file => file.split('/')[2].split('-')[0] + '-' + path.basename(file);
async function visit(file) {
  if (sources.has(file) || file === 'lib/chess.js') return;
  if (!file.startsWith('research/experiments/')) throw Error('Unexpected detector dependency: ' + file);
  const bytes = await readFile(path.join(root, file));
  const source = bytes.toString('utf8').replaceAll('\r\n', '\n'); sources.set(file, {source, sha256: hash(source)});
  for (const m of source.matchAll(/(?:from\s*|import\s*)['"]([^'"]+)['"]/g)) {
    await visit(path.posix.normalize(path.posix.join(path.posix.dirname(file), m[1])));
  }
}
await visit(entry);
await mkdir(path.join(root, destination), {recursive: true});
for (const [file, {source}] of sources) {
  const promoted = source.replace(/((?:from\s*|import\s*)['"])([^'"]+)(['"])/g, (_, a, specifier, z) => {
    const target = path.posix.normalize(path.posix.join(path.posix.dirname(file), specifier));
    return a + (target === 'lib/chess.js' ? '../../chess.js' : './' + name(target)) + z;
  }).replace(/\n+$/, '\n');
  await writeFile(path.join(root, destination, name(file)), promoted);
  sources.get(file).promotedSha256 = hash(promoted);
}
const trackerPath = 'research/experiments/E080-pawn-shield-defense/evidence/concept-status.md';
const tracker = (await readFile(path.join(root, trackerPath), 'utf8')).replaceAll('\r\n', '\n');
const verified = [...tracker.matchAll(/^- \[x\] (C\d{4}) \*\*([^*]+)\*\* — (.*)$/gm)]
  .map(([, occurrence, name, scope]) => ({occurrence, name, scope}));
await writeFile(path.join(root, 'lib/concepts/provenance.json'), JSON.stringify({
  study: 'E080', hashNormalization: 'utf8-lf', trackerPath, trackerSha256: hash(tracker), entry: name(entry),
  sources: Object.fromEntries([...sources].map(([file, {sha256, promotedSha256}]) => [file, {file: name(file), sha256, promotedSha256}])), verified,
}, null, 2) + '\n');
const code = [...sources.values()].map(v => v.source).join('\n');
const inputs = [...new Set([...code.matchAll(/(?:input|options)\.([A-Za-z]\w*)/g)].map(m => m[1]))];
const flags = inputs.filter(key => key.endsWith('Tags') || key === 'uniqueDefense');
const budgets = inputs.filter(key => /^max.*Nodes$/.test(key));
await writeFile(path.join(root, 'lib/concepts/profile.js'),
  '// Generated by scripts/promote-concepts.mjs. Budgets are explicit runtime limits.\n'
  + `export const FLAGS = ${JSON.stringify(flags)};\nexport const BUDGETS = ${JSON.stringify(budgets)};\n`
  + 'export const CONCEPT_VERSION = "E080-P001-v1";\n');
console.log(`Promoted ${sources.size} modules; ${verified.length} verified occurrence scopes.`);
