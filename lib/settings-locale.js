export function settingsTranslator(locale) {
  const simplifiedChinese = /^zh(?:[-_]Hans(?:[-_].*)?|[-_](?:CN|SG)|$)$/i.test(locale);
  return text => simplifiedChinese && Object.hasOwn(zhHans, text) ? zhHans[text] : text;
}

// Translate only the rendered settings controls. Internal values, dataset
// attributes and the accordion's state keys remain in their original form.
export function localizeSettings(root, translate) {
  const walker = root.ownerDocument.createTreeWalker(root, 4); // SHOW_TEXT
  while (walker.nextNode()) {
    const node = walker.currentNode;
    const translated = translate(node.data);
    if (translated !== node.data) node.data = translated;
  }
  for (const element of [root, ...root.querySelectorAll('[title], [aria-label]')]) {
    for (const attribute of ['title', 'aria-label']) {
      const value = element.getAttribute(attribute);
      if (value === null) continue;
      const translated = translate(value);
      if (translated !== value) element.setAttribute(attribute, translated);
    }
  }
}
